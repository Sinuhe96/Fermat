def parse_region_record(page: int) -> dict[str, dict]:
    """`01-extract/regions/pNNN.yml` -> {P0NNN-RM: {rect, crop, latex}}."""
    yml = REGIONS_DIR / f"p{page:03d}.yml"
    if not yml.exists():
        return {}
    out: dict[str, dict] = {}
    lines = yml.read_text(encoding="utf-8").splitlines()
    cur: str | None = None
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^\s*-\s+id:\s*(\S+)", line)
        if m:
            cur = f"P{page:03d}-{m.group(1)}"
            out[cur] = {"rect": None, "crop": None, "latex": ""}
            i += 1
            continue
        if cur:
            m = re.match(r"^\s*rect:\s*\[([^\]]*)\]", line)
            if m:
                try:
                    out[cur]["rect"] = [float(x) for x in m.group(1).split(",")]
                except ValueError:
                    out[cur]["rect"] = None
            m = re.match(r"^\s*crop:\s*(\S+)", line)
            if m:
                out[cur]["crop"] = m.group(1)
            if re.match(r"^\s*latex:\s*\|", line):
                indent = len(line) - len(line.lstrip())
                buf = []
                i += 1
                while i < len(lines):
                    nxt = lines[i]
                    nindent = len(nxt) - len(nxt.lstrip())
                    if nxt.strip() and nindent <= indent:
                        break
                    buf.append(nxt[indent + 2:] if len(nxt) > indent + 2 else "")
                    i += 1
                out[cur]["latex"] = "\n".join(buf).strip()
                continue
        i += 1
    return out


def page_points(page: int) -> tuple[float, float]:
    """Page size in PDF points from any region crop JSON for that page."""
    import json
    for j in sorted(RENDER_DIR.glob(f"page-{page:03d}-300dpi-region-*.json")):
        try:
            data = json.loads(j.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        rect = data.get("page_rect_points")
        if isinstance(rect, list) and len(rect) == 4:
            return float(rect[2] - rect[0]), float(rect[3] - rect[1])
    return PAGE_POINTS_DEFAULT


def png_size(path: Path) -> tuple[int, int]:
    data = path.read_bytes()[:24]
    if len(data) >= 24 and data[12:16] == b"IHDR":
        return struct.unpack(">II", data[16:24])
    return 0, 0


