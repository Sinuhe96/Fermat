def check(queries: list[dict], recs: dict[str, dict]) -> list[str]:
    warnings: list[str] = []
    query_ids = {q["id"] for q in queries}
    for q in queries:
        if q["chunk"] is None:
            warnings.append(f"{q['id']}: no chunk reference found")
        elif q["chunk"] not in recs:
            warnings.append(f"{q['id']}: references unknown chunk {q['chunk']}")
        for ref in IMAGE_REF_RE.findall(q["text"]):
            cand = ROOT / ref if ref.startswith("pipeline/") else HERE / ref
            if not cand.exists() and not (RENDER_DIR / Path(ref).name).exists():
                warnings.append(f"{q['id']}: image not found: {ref}")

    by_chunk: dict[str, list[str]] = {}
    for q in queries:
        if q["chunk"]:
            by_chunk.setdefault(q["chunk"], []).append(q["id"])
    for cid, rec in recs.items():
        if str(rec.get("status")) == "BLOCKED" and cid not in by_chunk:
            warnings.append(f"{cid}: BLOCKED but no author query references it")
        for qid in chunk_queries(rec):
            if qid not in query_ids:
                warnings.append(f"{cid}: mentions {qid}, but queries/{qid}-*.md is missing")
        for render in str(rec.get("renders", "")).split():
            if not (RENDER_DIR / render).exists():
                warnings.append(f"{cid}: render missing: {render}")
    return warnings


def prune(out_dir: Path) -> None:
    """Remove only what this script generated in *this* out dir (Gate 2:
    two report directories never share or inherit state)."""
    if not out_dir.exists():
        return
    entries = list(out_dir.iterdir())
    if not entries:
        return
    idx = out_dir / "index.html"
    if not (idx.exists() and MARKER
            in idx.read_text(encoding="utf-8", errors="replace")):
        print(f"error: {out_dir} exists but was not generated by {MARKER}; "
              f"refusing to delete it — use another --out", file=sys.stderr)
        raise SystemExit(2)
    for pattern in ("index.html", "Q-*.html", "reply-*.md", "*.zip"):
        for f in out_dir.glob(pattern):
            f.unlink()
    shutil.rmtree(out_dir / "assets", ignore_errors=True)


def _refs_in(text: str) -> list[str]:
    refs = list(re.findall(r"(?:src|href)=\"([^\"]+)\"", text))
    refs += [m[1] for m in re.findall(r"url\((['\"]?)([^)'\"]+)\1\)", text)]
    return refs


def verify(out_dir: Path, write_zip: bool) -> tuple[bool, str]:
    """Gate: zip the package, extract it elsewhere, and check that every
    reference resolves inside the extracted tree."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        zpath = tmp_path / "report.zip"
        files = sorted(p for p in out_dir.rglob("*") if p.is_file())
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as zf:
            for f in files:
                zf.write(f, f.relative_to(out_dir).as_posix())
        if write_zip:
            ship = out_dir.parent / (out_dir.name + ".zip")
            shutil.copy2(zpath, ship)
        extract = tmp_path / "x"
        extract.mkdir()
        with zipfile.ZipFile(zpath) as zf:
            zf.extractall(extract)

        problems: list[str] = []
        refs = 0
        root = extract.resolve()
        for page in sorted(extract.rglob("*")):
            if not page.is_file():
                continue
            suffix = page.suffix.lower()
            if suffix in (".html", ".htm"):
                text = page.read_text(encoding="utf-8", errors="replace")
                targets = [(r, page) for r in _refs_in(text)]
            elif suffix == ".css":
                text = page.read_text(encoding="utf-8", errors="replace")
                targets = [(m[1], page) for m in re.findall(r"url\((['\"]?)([^)'\"]+)\1\)", text)]
            else:
                continue
            for ref, base in targets:
                if EXTERNAL_REF_RE.match(ref):
                    continue
                refs += 1
                clean = unquote(ref.split("#")[0].split("?")[0])
                if not clean:
                    continue
                target = (base.parent / clean).resolve()
                try:
                    target.relative_to(root)
                except ValueError:
                    problems.append(f"{page.relative_to(extract)}: {ref} escapes the package")
                    continue
                if not target.exists():
                    problems.append(f"{page.relative_to(extract)}: missing {ref}")
        # Structural gate: a packed stylesheet must keep every @font-face (each
        # with its url()) and the rule that binds KaTeX's families — otherwise
        # formulas silently fall back to system fonts and look wrong.
        for css in sorted(extract.rglob("*.css")):
            rel = css.relative_to(extract).as_posix()
            dst = css.read_text(encoding="utf-8", errors="replace")
            blocks = dst.count("@font-face")
            with_url = len(re.findall(r"@font-face\{[^}]*url\(", dst))
            if blocks and blocks != with_url:
                problems.append(f"{rel}: {blocks - with_url} @font-face block(s) "
                                f"lost their url() font")
            if rel.startswith("assets/"):
                src_path = PIPE / rel[len("assets/"):]
                if src_path.is_file():
                    src_text = src_path.read_text(encoding="utf-8", errors="replace")
                    if src_text.count("@font-face") != blocks:
                        problems.append(f"{rel}: @font-face count {blocks} != source "
                                        f"{src_text.count('@font-face')}")
                    if ".katex{" in src_text and ".katex{" not in dst:
                        problems.append(f"{rel}: lost the .katex rule (font binding)")
            else:
                problems.append(f"{rel}: stylesheet outside assets/")

        size_mb = zpath.stat().st_size / (1024 * 1024)
        msg = (f"verify: {len(files)} files, {refs} refs checked, "
               f"zip {size_mb:.1f} MB -> extracted clean"
               if not problems else
               "verify FAILED:\n  " + "\n  ".join(problems))
        return (not problems), msg


# --------------------------------------------------------------------------- #

def main() -> int:
    ap = argparse.ArgumentParser(description="author report for Lean findings")
    ap.add_argument("--out", default=str(DEFAULT_OUT), metavar="DIR",
                    help="output directory (default: %(default)s)")
    ap.add_argument("--quiet", action="store_true", help="only errors on stdout")
    ap.add_argument("--no-verify", action="store_true",
                    help="skip the zip/extract self-containment gate")
    ap.add_argument("--zip", action="store_true",
                    help="also write <out>.zip for shipping")
    args = ap.parse_args()

    query_files = sorted(p for p in QUERIES_DIR.glob("Q-*.md")
                         if "template" not in p.stem.lower())
    if not query_files:
        print(f"error: no queries in {QUERIES_DIR}", file=sys.stderr)
        return 1

    queries: list[dict] = []
    for path in query_files:
        try:
            queries.append(parse_query(path))
        except ValueError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1

    recs: dict[str, dict] = {}
    for path in sorted(CHUNKS_DIR.glob("*.yml")):
        rec = parse_chunk(path)
        if rec.get("id"):
            recs[rec["id"]] = rec
    warnings = check(queries, recs)

    out_dir = Path(args.out)
    if not out_dir.is_absolute():
        out_dir = Path.cwd() / out_dir
    try:
        prune(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        print(f"error: cannot prepare {out_dir}: {exc}", file=sys.stderr)
        return 2

    pack = Pack(out_dir)
    try:
        # reply templates first: issue pages link to them
        for q in queries:
            rec = recs.get(q["chunk"] or "")
            (out_dir / f"reply-{q['id']}.md").write_text(
                build_reply(q, rec), encoding="utf-8", newline="\n")
        for q in queries:
            rec = recs.get(q["chunk"] or "")
            (out_dir / f"{q['id']}.html").write_text(
                build_issue_page(q, rec, pack), encoding="utf-8", newline="\n")
        (out_dir / "index.html").write_text(
            build_index(queries, recs, warnings, pack), encoding="utf-8", newline="\n")
        closure_added = pack.closure()
    except (OSError, FileNotFoundError) as exc:
        print(f"error: cannot build report: {exc}", file=sys.stderr)
        return 2

    ok, msg = True, "verify skipped (--no-verify)"
    if not args.no_verify:
        ok, msg = verify(out_dir, args.zip)
    if not args.quiet:
        print(f"report: {len(queries)} queries -> {out_dir / 'index.html'}")
        print(f"  packed {len(pack.map)} assets (+{closure_added} from linked pages), "
              f"{len(pack.html_queue)} linked pages")
        for q in queries:
            print(f"  {q['id']:<8} {q['status']:<9} chunk={q['chunk'] or '-':<12} "
                  f"{out_dir / (q['id'] + '.html')}")
        for d in pack.declined:
            print(f"  note: not packed (would drag the whole review surface): {d}")
        for w in warnings:
            print(f"  warning: {w}")
        print(f"  {msg}")
        if args.zip:
            print(f"  shipping archive: {out_dir.with_suffix('.zip')}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
