def highlights_for(query: dict, rec: dict | None) -> dict[int, list[tuple[list[float], str]]]:
    """page -> [(rect_points, region_id)] for the regions this query points at."""
    ids = REGION_ID_RE.findall(query["text"])
    if not ids and rec:
        ids = [s.strip() for s in str(rec.get("regions", "")).split(",") if s.strip()]
    pages = sorted({int(rid[1:4]) for rid in ids})
    out: dict[int, list[tuple[list[float], str]]] = {}
    for page in pages:
        regions = parse_region_record(page)
        sel = [(regions[rid]["rect"], rid) for rid in ids
               if int(rid[1:4]) == page and rid in regions and regions[rid]["rect"]]
        if sel:
            out[page] = sel
    return out


def highlight_latex(highlights: dict[int, list]) -> list[tuple[str, list[str]]]:
    """[(region_id, [display equations])] for the typeset-print card."""
    out = []
    for page in sorted(highlights):
        regions = parse_region_record(page)
        for _, rid in highlights[page]:
            tex = regions.get(rid, {}).get("latex", "")
            blocks = latex_blocks(tex)
            if blocks:
                out.append((rid, blocks))
    return out


def latex_blocks(tex: str) -> list[str]:
    if not tex.strip():
        return []
    found = re.findall(r"\\\[.*?\\\]", tex, re.S)
    if not found:
        return [tex.strip()]
    return [b[2:-2].strip() for b in found if b[2:-2].strip()]


