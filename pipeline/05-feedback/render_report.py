_TEX_MAP = [
    ("≢", r"\not\equiv"), ("≡", r"\equiv"), ("∤", r"\nmid"), ("∣", r"\mid"),
    ("⋮̸", r"\not\vdots"), ("⋮", r"\vdots"), ("ℤ", r"\mathbb{Z}"),
    ("ℕ", r"\mathbb{N}"), ("²", r"^{2}"), ("³", r"^{3}"), ("−", "-"),
    ("–", "-"), ("≤", r"\le"), ("≥", r"\ge"), ("≠", r"\ne"), ("∈", r"\in"),
    ("⇒", r"\Rightarrow"), ("→", r"\to"), ("↑", r"\uparrow"),
    ("·", r"\cdot "), ("…", r"\ldots "), ("*", " "),
]


def text_to_tex(s: str) -> str | None:
    """Best-effort conversion of a plain-text math fragment; None = leave alone."""
    if "/" in s or "\\" in s:            # paths / already-latex
        return None
    if not re.search(r"[\^≢≡∤∣²³]", s) and not re.search(r"\bmod\b", s):
        return None
    t = s
    for a, b in _TEX_MAP:
        t = t.replace(a, b)
    t = re.sub(r"\(mod\s+([^)]+)\)", r"\\pmod{\1}", t)
    t = re.sub(r"\^([A-Za-z0-9])", r"^{\1}", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t or None


def math_span(raw: str) -> str:
    """Inline math element with the raw text as no-JS/no-KaTeX fallback."""
    tex = text_to_tex(raw)
    if not tex:
        return f"<code>{html.escape(raw)}</code>"
    return (f'<span class="math-inline" data-tex="{html.escape(tex, quote=True)}" '
            f'data-raw="{html.escape(raw, quote=True)}">{html.escape(raw)}</span>')


def math_block(tex: str, raw: str | None = None) -> str:
    raw = raw if raw is not None else tex
    return (f'<div class="math-block" data-display="1" '
            f'data-tex="{html.escape(tex, quote=True)}" '
            f'data-raw="{html.escape(raw, quote=True)}">{html.escape(raw)}</div>')


