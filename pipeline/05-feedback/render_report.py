def _rel(target: Path, start: Path) -> str:
    """Relative URL from directory `start` to file `target`."""
    return Path(os.path.relpath(target, start)).as_posix()


def _code_span(escaped: str, pack: Pack) -> str:
    """`code` -> <code>, linked and packed when it names an existing repo file."""
    if PATH_REF_RE.fullmatch(escaped):
        cand = ROOT / escaped
        if pack.can_link(cand):
            return (f'<a href="{html.escape(pack.link(cand), quote=True)}">'
                    f"<code>{escaped}</code></a>")
    return f"<code>{escaped}</code>"


def _inline(segment: str, pack: Pack) -> str:
    """Bold, links, inline code and math inside an already-escaped segment."""
    parts = re.split(r"(`[^`]+`)", segment)
    for i, part in enumerate(parts):
        if part.startswith("`") and part.endswith("`") and len(part) > 2:
            inner = re.match(r"`(.*)`", part, re.S).group(1)
            parts[i] = math_span(html.unescape(inner)) if text_to_tex(html.unescape(inner)) \
                else _code_span(inner, pack)
            continue

        def sub_link(m: re.Match, _p=part) -> str:
            label, target = m.group(1), m.group(2)
            if EXTERNAL_REF_RE.match(target):
                return f'<a href="{html.escape(target, quote=True)}">{label}</a>'
            cand = ROOT / target
            if pack.can_link(cand):
                return (f'<a href="{html.escape(pack.link(cand), quote=True)}">'
                        f"{label}</a>")
            return label

        part = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", sub_link, part)
        part = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", part)
        parts[i] = part
    return "".join(parts)


def md_to_html(text: str, pack: Pack) -> str:
    out: list[str] = []
    para: list[str] = []
    code_buf: list[str] | None = None
    list_mode: str | None = None

    def flush_para() -> None:
        if para:
            out.append("<p>" + _inline(" ".join(para), pack) + "</p>")
            para.clear()

    def close_list() -> None:
        nonlocal list_mode
        if list_mode:
            out.append(f"</{list_mode}>")
            list_mode = None

    for raw in text.splitlines():
        line = raw.rstrip()
        if code_buf is not None:
            if line.strip().startswith("```"):
                out.append("<pre>" + html.escape("\n".join(code_buf)) + "</pre>")
                code_buf = None
            else:
                code_buf.append(raw)
            continue
        if line.strip().startswith("```"):
            flush_para()
            close_list()
            code_buf = []
            continue
        if not line.strip():
            flush_para()
            close_list()
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            flush_para()
            close_list()
            lvl = min(len(m.group(1)) + 1, 6)      # query text is sub-headings
            out.append(f"<h{lvl}>{_inline(html.escape(m.group(2)), pack)}</h{lvl}>")
            continue
        if line.startswith(">"):
            flush_para()
            close_list()
            out.append("<blockquote>" + _inline(html.escape(line.lstrip("> ")), pack)
                       + "</blockquote>")
            continue
        if re.match(r"^\s*[-*]\s+", line):
            flush_para()
            if list_mode != "ul":
                close_list()
                out.append("<ul>")
                list_mode = "ul"
            item = re.sub(r"^\s*[-*]\s+", "", line)
            out.append("<li>" + _inline(html.escape(item), pack) + "</li>")
            continue
        if re.match(r"^\s*\d+[.)]\s+", line):
            flush_para()
            if list_mode != "ol":
                close_list()
                out.append("<ol>")
                list_mode = "ol"
            item = re.sub(r"^\s*\d+[.)]\s+", "", line)
            out.append("<li>" + _inline(html.escape(item), pack) + "</li>")
            continue
        close_list()
        para.append(html.escape(line))
    if code_buf is not None:
        out.append("<pre>" + html.escape("\n".join(code_buf)) + "</pre>")
    flush_para()
    close_list()
    return "\n".join(out)


