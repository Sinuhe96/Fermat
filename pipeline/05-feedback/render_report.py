class Pack:
    """Copies/hardlinks every referenced file under <out>/assets, mirroring the
    pipeline-relative path, and reports the URL to use inside the report."""

    def __init__(self, out_dir: Path):
        self.out = out_dir
        self.assets = out_dir / "assets"
        self.map: dict[Path, Path] = {}
        self.html_queue: list[Path] = []
        self.css_queue: list[Path] = []
        self.declined: list[str] = []
        self._extern_names: dict[str, Path] = {}

    # -- link policy -------------------------------------------------------
    _SRC_LIST_RE = re.compile(r"src:([^;}]+)")
    _ENTRY_RE = re.compile(r"url\(([^)]+)\)\s*format\(([^)]+)\)")

    @classmethod
    def _trim_font_fallbacks(cls, css: str, base: Path) -> str:
        """Drop `url(...) format(...)` font entries whose file is not shipped,
        touching ONLY the inside of `src:` lists — a minified stylesheet puts
        `}@font-face{...` between entries, so a greedy pattern here destroys
        rules (that is what silently unbound the KaTeX fonts)."""
        def fix(m: re.Match) -> str:
            body = m.group(1)
            if "url(" not in body or "local(" in body:
                return m.group(0)
            entries = cls._ENTRY_RE.findall(body)
            if not entries:
                return m.group(0)
            keep = [f"url({u}) format({f})" for u, f in entries
                    if (base / u.strip("'\"")).is_file()]
            if not keep or len(keep) == len(entries):
                return m.group(0)
            return "src:" + ",".join(keep)

        return cls._SRC_LIST_RE.sub(fix, css)

    def can_link(self, src: Path) -> bool:
        if not src.is_file():
            return False
        if src.resolve() == (REVIEW_DIR / "index.html").resolve():
            # the review index links every manual page: packing it would drag
            # in the whole review surface; cite the individual pages instead.
            self.declined.append(str(src))
            return False
        return True

    def dest_for(self, src: Path) -> Path:
        try:
            rel = src.resolve().relative_to(PIPE.resolve())
            return self.assets / rel
        except ValueError:
            name = src.name
            prev = self._extern_names.get(name)
            if prev is not None and prev != src:
                name = f"{src.stem}-{abs(hash(str(src))) % 10 ** 8}{src.suffix}"
            self._extern_names[name] = src
            return self.assets / "_external" / name

    def link(self, src: Path) -> str:
        """Stage `src` into the package; return its URL relative to <out>."""
        src = src.resolve()
        if src.is_relative_to(self.out.resolve()):
            return _rel(src, self.out)
        if src in self.map:
            return _rel(self.map[src], self.out)
        if not src.is_file():
            raise FileNotFoundError(src)
        dest = self.dest_for(src)
        dest.parent.mkdir(parents=True, exist_ok=True)
        try:
            if src.suffix.lower() == ".css":
                # derived copy: keep only the font formats actually shipped
                # (KaTeX css lists woff2/woff/ttf; we ship woff2 only), so the
                # package never references a file it does not contain — and
                # never loses the @font-face/.katex rules that bind them.
                text = src.read_text(encoding="utf-8", errors="surrogateescape")
                derived = self._trim_font_fallbacks(text, src.parent)
                dest.write_text(derived, encoding="utf-8", errors="surrogateescape",
                                newline="\n")
                self.map[src] = dest
                self.css_queue.append(src)
                return _rel(dest, self.out)
            if dest.exists() and dest.stat().st_size != src.stat().st_size:
                dest.unlink()
            if not dest.exists():
                try:
                    os.link(src, dest)             # hardlink: no extra bytes
                except OSError:
                    shutil.copy2(src, dest)        # fallback (cross-device etc.)
        except OSError as exc:
            raise OSError(f"cannot stage {src}: {exc}") from exc
        self.map[src] = dest
        if src.suffix.lower() in (".html", ".htm"):
            self.html_queue.append(src)
        return _rel(dest, self.out)

    # -- closure over copied HTML -----------------------------------------
    def closure(self) -> int:
        """Copy whatever the *copied* HTML/CSS files reference (review pages →
        their renders/crops, KaTeX css → its woff2 fonts), so the package keeps
        working after a move."""
        seen: set[Path] = set()
        added = 0
        queue = list(self.html_queue) + list(self.css_queue)
        while queue:
            page = queue.pop()
            if page in seen:
                continue
            seen.add(page)
            text = page.read_text(encoding="utf-8", errors="replace")
            for ref in _refs_in(text):
                if EXTERNAL_REF_RE.match(ref):
                    continue
                clean = unquote(ref.split("#")[0].split("?")[0])
                if not clean:
                    continue
                target = (page.parent / clean).resolve()
                if not target.is_file():
                    continue
                if PIPE.resolve() not in target.parents and target.parent != PIPE.resolve():
                    continue                       # never pull files outside pipeline/
                if target in self.map:
                    continue
                before = len(self.map)
                try:
                    self.link(target)
                except OSError:
                    continue
                added += len(self.map) - before
                if target.suffix.lower() in (".html", ".htm", ".css"):
                    queue.append(target)
        return added


