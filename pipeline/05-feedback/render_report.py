#!/usr/bin/env python3
"""Author report generator for the Lean verification findings (05-feedback/).

Turns `queries/Q-NNN-*.md` + the chunk records (`02-chunks/chunks/*.yml`)
into a **self-contained** static HTML package the original author can read
without Lean and without the repository:

    report/index.html       overview: open queries, chunk status, how to respond
    report/Q-NNN.html       one page per issue: question first, the print with
                            highlighted regions, the LaTeX typeset, what Lean
                            verified, reply box
    report/reply-Q-NNN.md   plain-text reply template for answering by email
    report/assets/...       every referenced file (renders, region crops, review
                            pages, linked sources, KaTeX) — hardlinked when the
                            filesystem allows, copied otherwise

Self-containment is a gate: after writing, the script zips the report,
extracts it to a temp directory and checks that every `src`/`href` and every
CSS `url()` inside the package resolves **inside the package** (`--no-verify`
skips; `--zip` also writes `<out>.zip` for shipping). Each `--out` directory
owns its `assets/`, prunes its own generated files first, and never touches
another report directory.

Usage:
    python pipeline/05-feedback/render_report.py
    python pipeline/05-feedback/render_report.py --out report-v2 --zip

Exit codes: 0 report written and verified, 1 no/unparseable query or failed
verification, 2 output directory not writable / not generated by us.
"""

